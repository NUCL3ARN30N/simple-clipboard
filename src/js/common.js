function icon(name, cls = "icon") {
  return `<svg class="${cls}" viewBox="0 0 24 24" aria-hidden="true"><path d="${ICONS[name]}"/></svg>`;
}

function hydrateIcons(root = document) {
  root.querySelectorAll("[data-icon]").forEach((el) => {
    el.insertAdjacentHTML("afterbegin", icon(el.dataset.icon));
    el.removeAttribute("data-icon");
  });
}

const darkQuery = window.matchMedia("(prefers-color-scheme: dark)");

function applyTheme(settings) {
  const root = document.documentElement;
  const dark = settings.theme === "dark" || (settings.theme === "system" && darkQuery.matches);
  root.dataset.theme = dark ? "dark" : "light";
  root.style.setProperty("--accent", settings.accent || "#6750a4");
}

function escapeHtml(s) {
  return s.replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);
}

let snackTimer;
function snackbar(message) {
  let el = document.querySelector(".snackbar");
  if (!el) {
    el = document.createElement("div");
    el.className = "snackbar";
    document.body.appendChild(el);
  }
  el.textContent = message;
  el.classList.add("show");
  clearTimeout(snackTimer);
  snackTimer = setTimeout(() => el.classList.remove("show"), 2600);
}
